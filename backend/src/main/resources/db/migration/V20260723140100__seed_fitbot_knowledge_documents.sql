5. Tổ chức thực hiện tuyển sinh
- Phương thức 1:
● Phương thức 1a: Xét tuyển thẳng, ưu tiên xét tuyển theo Điều 8 Thông tư số 08/2022/TT-BGDĐT ngày 06
tháng 6 năm 2022 của Bộ trưởng Bộ Giáo dục và Đào tạo về việc ban hành Quy chế Tuyển sinh đại học,
tuyển sinh cao đẳng ngành Giáo dục Mầm non và các văn bản liên quan. Lưu ý mỗi ngành / nhóm ngành xét
tuyển sẽ có quy định về thứ tự ưu tiên cho các loại giải thưởng và thứ hạng giải thưởng được xét.
● Phương thức 1b: Xét tuyển dành cho thí sinh có quốc tịch nước ngoài và tốt nghiệp THPT của nước ngoài
● Điểm xét tuyển đối với diện Ưu tiên xét tuyển thẳng theo quy định của ĐHQG-HCM được tính theo công thức
như sau:
Điểm_xét_tuyển = ĐTB + ĐC (1)
Trong đó:
● ĐTB: Tổng điểm trung bình cộng kết quả học tập 03 năm lớp 10, 11 và 12 (hay kết quả
học tập của 03 năm học cuối cấp THPT của thí sinh).
● ĐC: Điểm cộng được quy định tại mục 4.b
● Trong trường hợp thí sinh có mức Điểm xét tuyển bằng nhau mà phải lựa chọn, Hội đồng
tuyển sinh sẽ căn cứ vào bài luận xét tuyển của thí sinh.
- Phương thức 2:
Xét tuyển dựa trên phương thức kết hợp kết quả kỳ thi tốt nghiệp THPT năm 2026 hay kết quả kỳ thi đánh giá năng lực
do ĐHQG-HCM tổ chức năm 2026 với điểm học bạ 03 năm lớp 10, 11, 12
Điểm_xét_tuyển = Điểm_học_lực + Điểm_cộng + Điểm_ưu_tiên (2)
Trong đó:
● Trường hợp 1: Đối với thí sinh có điểm thi THPT 2026
Điểm_học_lực_1 = w1 × Điểm_THPT + w2 × Điểm_học_bạ (3)
● Trường hợp 2: Đối với thí sinh có điểm kết quả kỳ thi đánh giá năng lực do ĐHQG-HCM tổ chức năm 2026
Điểm_học_lực_2 = w3 × Điểm_ĐGNL + w4 × Điểm_học_bạ (4)
Điểm_học_lực của (2) sẽ được tính là :
Điểm_học_lực = max (Điểm_học_lực_1, Điểm_học_lực_2) (5)
Trong các công thức trên, chi tiết các điểm thành phần được giải thích như sau:
● Điểm_học_bạ là tổng điểm trung bình trong học bạ của ba năm lớp 10, 11, 12 của 03 môn nằm trong một tổ
hợp của ngành / nhóm ngành (xem mục 3) có giá trị lớn nhất trong số các tổ hợp xét tuyển của ngành /
nhóm ngành. Điểm_học_bạ tính theo thang 30 điểm. Tổ hợp có đủ điểm 03 năm lớp 10, 11, 12 được ưu tiên
lựa chọn đầu tiên để tính trong công thức (3) và công thức (4). Trong trường hợp sau khi xét tất cả tổ hợp
nhưng thí sinh không có tổ hợp nào có đủ 03 môn cho 03 năm học lớp 10, 11, 12, thì điểm của 01 năm lớp
10 bị thiếu sẽ được quy đổi bằng trung bình điểm của 02 năm lớp 11 và lớp 12. Trong trường hợp kết quả
học tập của thí sinh không có tổ hợp môn nào có đủ 03 năm lớp 10, 11, 12 hay tổ hợp môn đủ 02 năm lớp 11,
12 thì Điểm_học_bạ và Điểm_học_lực sẽ được chọn là 0 điểm vì hồ sơ xét tuyển không hợp lệ.
● Điểm_THPT là tổng điểm 03 môn trong kỳ thi THPT 2026 của một tổ hợp có giá trị lớn nhất trong các tổ hợp
xét tuyển của ngành / nhóm ngành (mục 3). Điểm THPT tính theo thang 30 điểm. Điểm quy đổi tiếng Anh
của chứng chỉ ngoại ngữ quốc tế (TOEFL iBT hay IELTS) chỉ được áp dụng cho tổ hợp môn sử dụng kết quả
thi THPT trong đó có môn tiếng Anh.
● Điểm_ĐGNL là điểm thi ĐGNL lớn nhất của thí sinh trong 02 kỳ thi ĐGNL ĐHQG-HCM trong năm 2026.
Điểm_ĐGNL được quy đổi về thang 30 điểm để tính Điểm_học_lực theo công thức như sau:Điểm_ĐGNL =
(Điểm thi ĐGNL / Max_Điểm_thi_ĐGNL) × 30 (6)
Trong đó Max_Điểm_thi_ĐGNL là điểm thi lớn nhất xét trên tất cả thí sinh được công bố công khai của 02
đợt thi ĐGNL chính thức do ĐHQG-HCM tổ chức trong năm 2026 (không tính các kì thi bổ sung nếu có).
Điểm_ĐGNL trong công thức (4) và (5) là điểm thi lớn nhất của từng thí sinh tham gia xét tuyển vào Trường
có được sau 02 đợt thi ĐGNL trong năm 2026.
● Điểm_cộng là điểm cộng được tính dựa trên mục 4.b, lưu ý thí sinh chỉ được cộng 01 loại điểm cộng có mức
điểm cao nhất.
● Điểm_ưu_tiên là điểm ưu tiên khu vực đối tượng đối với thí sinh đạt tổng điểm từ 22,5 trở lên (khi quy đổi về
điểm theo thang 30) được xác định theo công thức sau:Điểm_ưu_tiên = [(30 – Tổng điểm đạt được) / 7,5] ×
Mức điểm ưu tiên KVĐT theo quy định của Bộ GDĐT (7)
Trong đó
Tổng điểm đạt được = Điểm_học_lực + Điểm_cộng (8)
● Các hệ số w1, w2, w3, w4 được xác định miền giá trị dựa trên hệ số hàm hồi quy tuyến tính nội suy biến đầu
ra là kết quả học tập đại học với các biến đầu vào là kết quả trúng tuyển theo điểm THPT, điểm ĐGNL kết
hợp với điểm học bạ của thí sinh ở các năm trước, bên cạnh tác động điều chỉnh của phân phối điểm của kì
thi THPT 2026 và kỳ thi ĐGNL do ĐHQG-HCM tổ chức trong năm 2026 . Hội đồng tuyển sinh sẽ xác định các
giá trị xác định w1, w2, w3, w4 khi công bố ngưỡng đảm bảo chất lượng. Hiện nay miền giá trị của w1, w3
được xác định là [0.7, 0.9] và miền giá trị của w2, w4 là [0.1, 0.3]
● Kết quả trúng tuyển của Phương thức 2 là Điểm_xét_tuyển_công_bố được chuẩn hóa trên thang điểm theo
quy định của ĐHQG-HCM (lấy đến 2 chữ số thập phân):Điểm_xét_tuyển_công_bố = Thang_điểm_ĐHQG-HCM
× (Điểm_xét_tuyển / 30) (9)
