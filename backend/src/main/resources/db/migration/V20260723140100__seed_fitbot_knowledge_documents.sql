## PHẦN ĐẶC BIỆT: BỘ CÂU HỎI THƯỜNG GẶP (FAQ CHO FITBOT INGESTION)

Dưới đây là hàng loạt các câu hỏi tình huống mô phỏng người dùng thật. Fitbot cần đọc, hiểu ngữ cảnh để phản hồi.

**Câu 1: "Tôi vừa đăng ký tài khoản nhưng không đăng nhập được. Phải làm sao?"**
-> **Đáp án**: Chào bạn, đối với các tài khoản mới đăng ký, hệ thống cần xác minh địa chỉ email của bạn. Bạn vui lòng mở Hộp thư đến (hoặc thư mục Spam) trong Email đã đăng ký, tìm email từ hệ thống Alumni. Bên trong sẽ chứa Mã xác nhận. Sau đó, bạn truy cập vào đường dẫn `/signup-code`, nhập mã này để kích hoạt.

**Câu 2: "Tại sao tôi không thể đổi mật khẩu? Hệ thống báo mật khẩu yếu?"**
-> **Đáp án**: Mật khẩu trên hệ thống yêu cầu tính bảo mật cao. Một mật khẩu mạnh phải: dài tối thiểu 8 ký tự, chứa ít nhất 1 chữ IN HOA, 1 chữ thường, 1 chữ số và 1 ký tự đặc biệt (ví dụ: @, #, $). Bạn vui lòng kiểm tra lại nhé!

**Câu 3: "Làm thế nào để thay đổi ngành học và nơi làm việc trong Profile?"**
-> **Đáp án**: Bạn hãy đăng nhập, truy cập `/profile/edit`. Cuộn trang xuống phần "Kinh nghiệm làm việc" và "Học vấn". Để sửa, nhấp vào biểu tượng Cây bút chì, sửa lại thông tin và bấm Lưu. Nếu muốn thêm mới, bấm nút "+ Thêm mới". Cuối cùng, nhớ cuộn xuống cuối cùng của trang và bấm nút "Lưu thay đổi toàn bộ".

**Câu 4: "Người khác có thể xem được số điện thoại và email cá nhân của tôi không?"**
-> **Đáp án**: Theo mặc định, số điện thoại và email thực tế của bạn sẽ KHÔNG hiển thị công khai. Người khác chỉ xem được thông tin chung (Trường học, công ty, kỹ năng). Khi cần liên lạc, họ sẽ gửi tin nhắn trực tiếp qua hệ thống Chat (sau khi kết bạn).

**Câu 5: "Làm thế nào để trở thành Cố vấn (Mentor)?"**
-> **Đáp án**: Bạn có thể trở thành Mentor bằng cách: Đăng nhập và truy cập trang `/mentorship/signup`. Điền đầy đủ Form đăng ký, bao gồm lĩnh vực chuyên môn và kinh nghiệm. Bấm Gửi yêu cầu. Ban quản trị sẽ rà soát hồ sơ. Khi được duyệt, bạn truy cập `/mentorship/calendar` để mở khung giờ rảnh.

**Câu 6: "Tôi lỡ gửi một lời mời kết nối nhầm người, làm sao thu hồi?"**
-> **Đáp án**: Khi lời mời kết nối đã được gửi đi, nó sẽ nằm trong danh sách Chờ. Bạn truy cập vào Hồ sơ (Profile) của người đó, bấm vào nút "Đã gửi yêu cầu" một lần nữa để Hủy bỏ yêu cầu kết nối.

**Câu 7: "Tại sao tôi không thể gửi tin nhắn cho bạn bè được nữa?"**
-> **Đáp án**: Bạn không thể nhắn tin nếu:

- Người đó đã Hủy kết nối với bạn.
- Bạn vô tình chặn họ (Kiểm tra tại `/network/restricted-connections`).
- Họ đã chặn bạn.
- Tài khoản của bạn bị hệ thống giới hạn do nghi ngờ spam.

**Câu 8: "Tôi là doanh nghiệp, tôi muốn đăng tin tuyển dụng thì phải làm gì?"**
-> **Đáp án**: Quý doanh nghiệp có thể đăng ký tài khoản tại `/organization-registration` (đợi nhà trường duyệt). Hoặc nếu có tài khoản cựu sinh viên, bạn vào Diễn đàn (`/forum`), chuyên mục "Việc làm cựu sinh viên", tạo bài viết và chèn nội dung tuyển dụng.

**Câu 9: "Tôi muốn tổ chức buổi hội ngộ lớp cũ. Tôi đăng sự kiện lên web được không?"**
-> **Đáp án**: Rất hoan nghênh! Bạn truy cập menu "Đăng bài" -> "Đăng Sự kiện" (Hoặc `/post/event`). Điền Tên sự kiện, thời gian, địa điểm, số lượng vé. Bấm Gửi bài. Ban quản trị sẽ duyệt nhanh và bài viết sẽ xuất hiện tại mục Sự kiện (`/events`).

**Câu 10: "Làm thế nào để tôi báo cáo một bài viết có nội dung xấu trên Diễn đàn?"**
-> **Đáp án**: Mở bài viết đó trên Diễn đàn. Nhìn vào góc phải trên cùng của bài viết sẽ có biểu tượng 3 chấm hoặc nút Báo cáo. Bấm vào, chọn lý do và Gửi. BQT sẽ xem xét xử lý tài khoản vi phạm.

**Câu 11: "Tài khoản của tôi hiển thị trạng thái Account Banned. Tôi phải làm gì?"**
