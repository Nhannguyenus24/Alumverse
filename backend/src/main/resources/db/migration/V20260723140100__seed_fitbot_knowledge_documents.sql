**2. Đối tượng được phép sử dụng (Phân quyền truy cập):**

- Chỉ dành cho Thành viên đã đăng nhập (Logged-in Users).
- Lưu ý: Những tài khoản đang trong trạng thái khóa hoặc bị hạn chế (Restricted) có thể không truy cập được hoặc bị giới hạn một phần tính năng này nhằm đảm bảo tính an toàn cho cộng đồng.

**3. Đường dẫn truy cập (URL Mapping):**

- Người dùng truy cập qua đường dẫn: `/post/:channel`
- Bạn có thể dễ dàng sao chép đường dẫn này để chia sẻ cho bạn bè. Khi chia sẻ đường dẫn, hệ thống sẽ yêu cầu người nhận phải đăng nhập (nếu tính năng yêu cầu tài khoản).

**4. Mô tả các thành phần Giao diện:**
Để sử dụng hiệu quả, người dùng cần nhận biết các thành phần chính trên giao diện trang này:

- **Thanh điều hướng**: Nằm ở trên cùng, chứa Logo (bấm vào để về trang chủ), Menu chính, Khung tìm kiếm, Icon Thông báo và Avatar cá nhân.
- **Khu vực Nội dung chính**: Hiển thị dữ liệu chính yếu của trang. Dữ liệu được phân chia thành các danh mục rõ ràng giúp người dùng dễ dàng theo dõi.
- **Biểu mẫu điền thông tin (Nếu có)**: Được thiết kế trực quan, có chú thích rõ ràng ở từng ô để người dùng biết cần nhập thông tin gì.
- **Các Nút thao tác**: Mang màu sắc nổi bật để chỉ dẫn người dùng hoàn tất thao tác (Ví dụ: Nút Đăng ký, Nút Gửi, Nút Kết nối).

**5. Hướng dẫn Thao tác từng bước:**
Đây là quy trình thao tác chuẩn, được thiết kế vô cùng đơn giản để ai cũng có thể làm quen nhanh chóng:

- **Bước 1**: Nhấp vào liên kết trên thanh menu hoặc nhập URL `/post/:channel` vào trình duyệt.
- **Bước 2**: Chờ giao diện hiển thị đầy đủ thông tin. Đọc kỹ các hướng dẫn trên màn hình.
- **Bước 3**: Tìm kiếm, nhấp chọn hoặc điền thông tin vào biểu mẫu (tùy thuộc vào yêu cầu của tính năng). Đảm bảo kiểm tra kỹ thông tin cá nhân khi nhập liệu.
- **Bước 4**: Bấm vào nút xác nhận cuối cùng để hoàn tất thao tác (Ví dụ: Lưu thay đổi, Xác nhận đăng ký).
- **Bước 5**: Chú ý thông báo xác nhận thành công hiển thị trên màn hình. Nếu hệ thống báo lỗi, hãy đọc kỹ thông báo màu đỏ để điều chỉnh.

**6. Xử lý các Lỗi Thường Gặp (Troubleshooting):**

- **Lỗi nhập thiếu thông tin**: Khi bạn nhập sót một trường bắt buộc, hệ thống sẽ báo đỏ. Bạn chỉ cần bổ sung thông tin và bấm gửi lại.
- **Lỗi kết nối**: Nếu màn hình load quá lâu, vui lòng kiểm tra lại mạng wifi hoặc 4G của bạn, sau đó làm mới trang.
- **Lỗi hết hạn đăng nhập**: Vui lòng đăng nhập lại để tiếp tục sử dụng.

